class VarifocalLoss(nn.Module):
    """
    Varifocal loss by Zhang et al.

    Implements the Varifocal Loss function for addressing class imbalance in object detection by focusing on
    hard-to-classify examples and balancing positive/negative samples.

    Attributes:
        gamma (float): The focusing parameter that controls how much the loss focuses on hard-to-classify examples.
        alpha (float): The balancing factor used to address class imbalance.

    References:
        https://arxiv.org/abs/2008.13367
    """

    def __init__(self, gamma: float = 2.0, alpha: float = 0.75):
        """Initialize the VarifocalLoss class with focusing and balancing parameters."""
        super().__init__()
        self.gamma = gamma
        self.alpha = alpha

    def forward(self, pred_score: torch.Tensor, gt_score: torch.Tensor, label: torch.Tensor) -> torch.Tensor:
        """Compute varifocal loss between predictions and ground truth."""
        weight = self.alpha * pred_score.sigmoid().pow(self.gamma) * (1 - label) + gt_score * label
        with autocast(enabled=False):
            loss = (
                (F.binary_cross_entropy_with_logits(pred_score.float(), gt_score.float(), reduction="none") * weight)
                .mean(1)
                .sum()
            )
        return loss


class FocalLoss(nn.Module):
    """
    Wraps focal loss around existing loss_fcn(), i.e. criteria = FocalLoss(nn.BCEWithLogitsLoss(), gamma=1.5).

    Implements the Focal Loss function for addressing class imbalance by down-weighting easy examples and focusing
    on hard negatives during training.

    Attributes:
        gamma (float): The focusing parameter that controls how much the loss focuses on hard-to-classify examples.
        alpha (torch.Tensor): The balancing factor used to address class imbalance.
    """

    def __init__(self, gamma: float = 1.5, alpha: float = 0.25):
        """Initialize FocalLoss class with focusing and balancing parameters."""
        super().__init__()
        self.gamma = gamma
        self.alpha = torch.tensor(alpha)

    def forward(self, pred: torch.Tensor, label: torch.Tensor) -> torch.Tensor:
        """Calculate focal loss with modulating factors for class imbalance."""
        loss = F.binary_cross_entropy_with_logits(pred, label, reduction="none")
        # p_t = torch.exp(-loss)
        # loss *= self.alpha * (1.000001 - p_t) ** self.gamma  # non-zero power for gradient stability

        # TF implementation https://github.com/tensorflow/addons/blob/v0.7.1/tensorflow_addons/losses/focal_loss.py
        pred_prob = pred.sigmoid()  # prob from logits
        p_t = label * pred_prob + (1 - label) * (1 - pred_prob)
        modulating_factor = (1.0 - p_t) ** self.gamma
        loss *= modulating_factor
        if (self.alpha > 0).any():
            self.alpha = self.alpha.to(device=pred.device, dtype=pred.dtype)
            alpha_factor = label * self.alpha + (1 - label) * (1 - self.alpha)
            loss *= alpha_factor
        return loss.mean(1).sum()


class DFLoss(nn.Module):
    """Criterion class for computing Distribution Focal Loss (DFL)."""

    def __init__(self, reg_max: int = 16) -> None:
        """Initialize the DFL module with regularization maximum."""
        super().__init__()
        self.reg_max = reg_max

    def __call__(self, pred_dist: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        """Return sum of left and right DFL losses from https://ieeexplore.ieee.org/document/9792391."""
        target = target.clamp_(0, self.reg_max - 1 - 0.01)
        tl = target.long()  # target left
        tr = tl + 1  # target right
        wl = tr - target  # weight left
        wr = 1 - wl  # weight right
        return (
            F.cross_entropy(pred_dist, tl.view(-1), reduction="none").view(tl.shape) * wl
            + F.cross_entropy(pred_dist, tr.view(-1), reduction="none").view(tl.shape) * wr
        ).mean(-1, keepdim=True)


class BboxLoss(nn.Module):
    """Criterion class for computing training losses for bounding boxes."""

    def __init__(self, reg_max: int = 16):
        """Initialize the BboxLoss module with regularization maximum and DFL settings."""
        super().__init__()
        self.dfl_loss = DFLoss(reg_max) if reg_max > 1 else None

    def forward(
        self,
        pred_dist: torch.Tensor,
        pred_bboxes: torch.Tensor,
        anchor_points: torch.Tensor,
        target_bboxes: torch.Tensor,
        target_scores: torch.Tensor,
        target_scores_sum: torch.Tensor,
        fg_mask: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Compute IoU and DFL losses for bounding boxes."""
        weight = target_scores.sum(-1)[fg_mask].unsqueeze(-1)
        iou = bbox_iou(pred_bboxes[fg_mask], target_bboxes[fg_mask], xywh=False, CIoU=True)
        loss_iou = ((1.0 - iou) * weight).sum() / target_scores_sum

        # DFL loss
        if self.dfl_loss:
            target_ltrb = bbox2dist(anchor_points, target_bboxes, self.dfl_loss.reg_max - 1)
            loss_dfl = self.dfl_loss(pred_dist[fg_mask].view(-1, self.dfl_loss.reg_max), target_ltrb[fg_mask]) * weight
            loss_dfl = loss_dfl.sum() / target_scores_sum
        else:
            loss_dfl = torch.tensor(0.0).to(pred_dist.device)

        return loss_iou, loss_dfl


class RotatedBboxLoss(BboxLoss):
    """Criterion class for computing training losses for rotated bounding boxes."""

    def __init__(self, reg_max: int):
        """Initialize the RotatedBboxLoss module with regularization maximum and DFL settings."""
        super().__init__(reg_max)

    def forward(
        self,
        pred_dist: torch.Tensor,
        pred_bboxes: torch.Tensor,
        anchor_points: torch.Tensor,
        target_bboxes: torch.Tensor,
        target_scores: torch.Tensor,
        target_scores_sum: torch.Tensor,
        fg_mask: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Compute IoU and DFL losses for rotated bounding boxes."""
        weight = target_scores.sum(-1)[fg_mask].unsqueeze(-1)
        iou = probiou(pred_bboxes[fg_mask], target_bboxes[fg_mask])
        loss_iou = ((1.0 - iou) * weight).sum() / target_scores_sum

        # DFL loss
        if self.dfl_loss:
            target_ltrb = bbox2dist(anchor_points, xywh2xyxy(target_bboxes[..., :4]), self.dfl_loss.reg_max - 1)
            loss_dfl = self.dfl_loss(pred_dist[fg_mask].view(-1, self.dfl_loss.reg_max), target_ltrb[fg_mask]) * weight
            loss_dfl = loss_dfl.sum() / target_scores_sum
        else:
            loss_dfl = torch.tensor(0.0).to(pred_dist.device)

        return loss_iou, loss_dfl


class KeypointLoss(nn.Module):
    """Criterion class for computing keypoint losses."""

    def __init__(self, sigmas: torch.Tensor) -> None:
        """Initialize the KeypointLoss class with keypoint sigmas."""
        super().__init__()
        self.sigmas = sigmas

    def forward(
        self, pred_kpts: torch.Tensor, gt_kpts: torch.Tensor, kpt_mask: torch.Tensor, area: torch.Tensor
    ) -> torch.Tensor:
        """Calculate keypoint loss factor and Euclidean distance loss for keypoints."""
        d = (pred_kpts[..., 0] - gt_kpts[..., 0]).pow(2) + (pred_kpts[..., 1] - gt_kpts[..., 1]).pow(2)
        kpt_loss_factor = kpt_mask.shape[1] / (torch.sum(kpt_mask != 0, dim=1) + 1e-9)
        # e = d / (2 * (area * self.sigmas) ** 2 + 1e-9)  # from formula
        e = d / ((2 * self.sigmas).pow(2) * (area + 1e-9) * 2)  # from cocoeval
        return (kpt_loss_factor.view(-1, 1) * ((1 - torch.exp(-e)) * kpt_mask)).mean()


# [TPAMI Innovation 1] EDL with Soft Targets (Evidence-based Uncertainty)
# 解决了 Soft Label 与传统 EDL 硬分类假设冲突的问题
# ==============================================================================
class EUR(nn.Module):
    """
    Dirichlet-based Evidential Deep Learning Loss compatible with Soft Targets.
    """
    def __init__(self, num_classes: int, annealing_step: int = 20, eps: float = 1e-7, logit_clip: float = 20.0):
        super().__init__()
        self.num_classes = num_classes
        self.annealing_step = annealing_step
        self.eps = eps
        self.logit_clip = logit_clip

    def kl_divergence_to_uniform(self, alpha: torch.Tensor) -> torch.Tensor:
        """Calculate KL( Dir(alpha) || Dir(1) )"""
        N, C = alpha.shape
        beta = torch.ones((1, C), dtype=alpha.dtype, device=alpha.device)
        S_alpha = alpha.sum(dim=1, keepdim=True)
        S_beta = beta.sum(dim=1, keepdim=True)
        
        lnB_alpha = torch.lgamma(S_alpha) - torch.sum(torch.lgamma(alpha), dim=1, keepdim=True)
        lnB_beta  = torch.sum(torch.lgamma(beta), dim=1, keepdim=True) - torch.lgamma(S_beta)
        
        dg0 = torch.digamma(S_alpha)
        dg1 = torch.digamma(alpha)
        
        kl = lnB_alpha + lnB_beta + torch.sum((alpha - beta) * (dg1 - dg0), dim=1, keepdim=True)
        return kl

    def forward(self, pred_logits: torch.Tensor, target_soft: torch.Tensor, current_epoch: int) -> torch.Tensor:
        """
        pred_logits: [N, C] (Positive samples only)
        target_soft: [N, C] (Soft labels from Assigner)
        """
        if pred_logits.numel() == 0:
            return torch.tensor(0.0, device=pred_logits.device)

        # 1. Clip logits for numerical stability (防止 exp 溢出)
        pred_logits = pred_logits.clamp(min=-self.logit_clip, max=self.logit_clip)
        
        # 2. Evidence computation (Softplus ensures non-negative)
        evidence = F.softplus(pred_logits)
        alpha = evidence + 1.0
        S = alpha.sum(dim=1, keepdim=True)

        # 3. Target Normalization (Crucial for Soft Labels)
        # Detach targets to stop gradient flowing back to Assigner
        y = target_soft.detach().to(alpha.dtype) 
        y_sum = y.sum(dim=1, keepdim=True)
        y = y / (y_sum + self.eps)

        # 4. EDL Risk (Type II Maximum Likelihood)
        # L = sum( y * (log(S) - digamma(alpha)) )
        a_loss = torch.sum(y * (torch.log(S + self.eps) - torch.digamma(alpha)), dim=1, keepdim=True)

        # 5. KL Regularization
        # Only penalize deviation from uniform for "non-target" mass (1-y)
        # This allows the model to be uncertain about ambiguous classes
        kl_alpha = (alpha - 1.0) * (1.0 - y) + 1.0 
        kl_div = self.kl_divergence_to_uniform(kl_alpha)

        # Annealing strategy
        anneal = min(1.0, float(current_epoch) / float(self.annealing_step))
        
        return torch.mean(a_loss + anneal * kl_div)

# [TPAMI Innovation 2] Stable Riemannian Manifold Loss (Contrastive)
# 使用 Supervised Contrastive Learning 显式约束特征流形
class SCML(nn.Module):
    """Supervised contrastive manifold loss using features at ground-truth centers."""

    def __init__(self, temperature=0.07, weight=0.05, size_thresh=(64, 128), max_samples=128, max_per_class=16):
        super().__init__()
        self.t = temperature
        self.w = weight
        self.th1, self.th2 = size_thresh
        self.max_samples = max_samples
        self.max_per_class = max_per_class
        self.eps = 1e-8

    @torch.no_grad()
    def _assign_level(self, wh_px, n_levels):
        area = wh_px[:, 0] * wh_px[:, 1]
        s = torch.sqrt(area.clamp(min=0.0))
        lvl = torch.zeros_like(s, dtype=torch.long)
        lvl = torch.where(s >= self.th1, torch.ones_like(lvl), lvl)
        lvl = torch.where(s >= self.th2, torch.full_like(lvl, 2), lvl)
        return torch.clamp(lvl, 0, n_levels - 1)

    @torch.no_grad()
    def _balanced_sample(self, cls_ids):
        device = cls_ids.device
        uniq = cls_ids.unique()
        chosen = []
        for c in uniq:
            idx = torch.where(cls_ids == c)[0]
            if idx.numel() > self.max_per_class:
                perm = torch.randperm(idx.numel(), device=device)[:self.max_per_class]
                idx = idx[perm]
            chosen.append(idx)
        
        if not chosen: 
            return torch.empty(0, dtype=torch.long, device=device)
        
        idx_all = torch.cat(chosen)
        if idx_all.numel() > self.max_samples:
            perm = torch.randperm(idx_all.numel(), device=device)[:self.max_samples]
            idx_all = idx_all[perm]
        return idx_all

    def _supcon_loss(self, features, labels):
        M = features.shape[0]
        if M < 2: return torch.tensor(0.0, device=features.device)
        
        logits = (features @ features.t()) / self.t
        labels = labels.view(-1, 1)
        mask = torch.eq(labels, labels.t()).float()
        
        logits_mask = torch.scatter(torch.ones_like(mask), 1, torch.arange(M, device=features.device).view(-1, 1), 0)
        mask = mask * logits_mask 
        
        logits_max, _ = torch.max(logits, dim=1, keepdim=True)
        logits = logits - logits_max.detach()
        
        exp_logits = torch.exp(logits) * logits_mask
        log_prob = logits - torch.log(exp_logits.sum(1, keepdim=True) + self.eps)
        
        mask_sum = mask.sum(1)
        mask_valid = mask_sum > 0
        # [Fix] 显式转换 any() 为 item() 防止 Tensor 判定报错
        if not mask_valid.any().item(): 
            return torch.tensor(0.0, device=features.device)
        
        mean_log_prob_pos = (mask[mask_valid] * log_prob[mask_valid]).sum(1) / mask_sum[mask_valid]
        return -mean_log_prob_pos.mean()

    def forward(self, feats, targets, strides):
        if targets is None or targets.numel() == 0: 
            return torch.tensor(0.0, device=feats[0].device)
        
        device = feats[0].device
        total_loss = torch.tensor(0.0, device=device)
        valid_levels = 0
        
        b_idx, cls, xy, wh = targets[:, 0].long(), targets[:, 1].long(), targets[:, 2:4], targets[:, 4:6]
        valid_mask = (b_idx >= 0) & (b_idx < feats[0].shape[0])
        b_idx, cls, xy, wh = b_idx[valid_mask], cls[valid_mask], xy[valid_mask], wh[valid_mask]
        
        if b_idx.numel() == 0: return total_loss

        H0, W0 = feats[0].shape[2:]
        s0 = strides[0]
        wh_px = wh * torch.tensor([W0 * s0, H0 * s0], device=device)
        levels = self._assign_level(wh_px, len(feats))

        for i, feat in enumerate(feats):
            mask = (levels == i)
            # [Fix] 显式使用 .item() 
            if mask.sum().item() < 2: continue
            
            cls_sub, b_sub, xy_sub = cls[mask], b_idx[mask], xy[mask]
            final_idx = self._balanced_sample(cls_sub)
            if final_idx.numel() < 2: continue
            
            b_fin, cls_fin, xy_fin = b_sub[final_idx], cls_sub[final_idx], xy_sub[final_idx]
            
            _, _, H, W = feat.shape
            gx = (xy_fin[:, 0] * W).long().clamp(0, W-1)
            gy = (xy_fin[:, 1] * H).long().clamp(0, H-1)
            
            target_feats = F.normalize(feat[b_fin, :, gy, gx], dim=1)
            loss = self._supcon_loss(target_feats, cls_fin)
            
            # [Fix] 显式使用 .item()
            if loss.item() > 0:
                total_loss += loss
                valid_levels += 1
                
        if valid_levels > 0:
            return (total_loss / valid_levels) * self.w
        return torch.tensor(0.0, device=device)


class UECO:
    """Unified Evidential-Contrastive Objective for PhysFlowNet detection."""
    """Criterion class for computing training losses for YOLOv8 object detection."""

    def __init__(self, model):  
        self.model = model
        device = next(model.parameters()).device  
        h = model.args  

        m = model.model[-1]  
        self.bce = nn.BCEWithLogitsLoss(reduction="none")
        self.hyp = h
        self.stride = m.stride  
        self.nc = m.nc  
        self.no = m.no
        self.reg_max = m.reg_max
        self.device = device
        self.use_dfl = m.reg_max > 1
        self.assigner = TaskAlignedAssigner(topk=10, num_classes=self.nc, alpha=0.5, beta=6.0)
        self.bbox_loss = BboxLoss(m.reg_max).to(device)
        self.proj = torch.arange(m.reg_max, dtype=torch.float, device=device)

        # 1. EDL Loss
        total_epochs = getattr(h, 'epochs', 400) if not isinstance(h, dict) else h.get('epochs', 400)
        self.edl_loss = EUR(
            num_classes=self.nc, 
            annealing_step=min(50, max(1, total_epochs // 3)),
            logit_clip=20.0
        )
        
        # 2. Manifold Loss
        strides_list = self.stride.tolist() if isinstance(self.stride, torch.Tensor) else self.stride
        self.manifold_loss = SCML(
            temperature=0.07, weight=0.05, size_thresh=(64, 128), max_samples=64, max_per_class=16
        )
        self.strides_list = strides_list
        
        # [移除强行修改 loss_names 的黑魔法，迎合验证器框架的铁律]

    def preprocess(self, targets, batch_size, scale_tensor):
        if targets.shape[0] == 0:
            out = torch.zeros(batch_size, 0, 5, device=self.device)
        else:
            i = targets[:, 0]  
            _, counts = i.unique(return_counts=True)
            counts = counts.to(dtype=torch.int32)
            out = torch.zeros(batch_size, counts.max(), 5, device=self.device)
            for j in range(batch_size):
                matches = i == j
                n = matches.sum()
                # [Fix] 显式 .item()
                if n.item():
                    out[j, :n] = targets[matches, 1:]
            out[..., 1:5] = xywh2xyxy(out[..., 1:5].mul_(scale_tensor))
        return out

    def bbox_decode(self, anchor_points, pred_dist):
        if self.use_dfl:
            b, a, c = pred_dist.shape  
            pred_dist = pred_dist.view(b, a, 4, c // 4).softmax(3).matmul(self.proj.type(pred_dist.dtype))
        return dist2bbox(pred_dist, anchor_points, xywh=False)

    def __call__(self, preds, batch):
        feats = None
        raw_features = None
        
        if isinstance(preds, dict):
            feats = preds.get("one2many")
            raw_features = preds.get("raw_features", feats) 
        elif isinstance(preds, tuple):
            # ========================================================
            # [Validation Fix] 智能区分训练阶段和验证阶段的 Tuple 结构
            # ========================================================
            if isinstance(preds[0], list) and isinstance(preds[1], list):
                # 1. 训练阶段: PhysFlowNetDetect 返回 (x, x_raw)
                feats, raw_features = preds[0], preds[1]
            elif isinstance(preds[1], list):
                # 2. 验证阶段常规模式: 返回 (y, x)
                feats, raw_features = preds[1], preds[1]
            elif isinstance(preds[1], dict):
                # 3. 验证阶段端到端模式: 返回 (y, {"one2many": x, ...})
                feats = preds[1].get("one2many")
                raw_features = preds[1].get("raw_features", feats)
            else:
                feats = preds[1]
                raw_features = preds[1]
        elif isinstance(preds, list):
            feats = preds
            raw_features = preds
        else:
            raise RuntimeError(f"Invalid preds structure passed to Loss. Type: {type(preds)}")

        # 严格防范隐式 Tensor Boolean 判断
        if feats is None or not isinstance(feats, list) or len(feats) == 0:
            raise RuntimeError("Failed to extract valid feature maps from predictions.")

        # =============================================================
        # 2. [Auto-Config] 强制同步通道数 (防御性编程)
        # =============================================================
        actual_channels = feats[0].shape[1]
        if actual_channels != self.no:
            self.no = actual_channels
            estimated_nc = self.no - (self.reg_max * 4)
            if estimated_nc > 0:
                self.nc = estimated_nc

        # [恢复为标准的 3 长度 Tensor 防止框架验证器报错]
        loss = torch.zeros(3, device=self.device)  

        pred_distri, pred_scores = torch.cat([xi.view(feats[0].shape[0], self.no, -1) for xi in feats], 2).split(
            (self.reg_max * 4, self.nc), 1
        )
        pred_scores = pred_scores.permute(0, 2, 1).contiguous()
        pred_distri = pred_distri.permute(0, 2, 1).contiguous()

        dtype = pred_scores.dtype
        batch_size = pred_scores.shape[0]
        imgsz = torch.tensor(feats[0].shape[2:], device=self.device, dtype=dtype) * self.stride[0]
        anchor_points, stride_tensor = make_anchors(feats, self.stride, 0.5)

        targets = torch.cat((batch["batch_idx"].view(-1, 1), batch["cls"].view(-1, 1), batch["bboxes"]), 1)
        targets = self.preprocess(targets.to(self.device), batch_size, scale_tensor=imgsz[[1, 0, 1, 0]])
        gt_labels, gt_bboxes = targets.split((1, 4), 2)  
        mask_gt = gt_bboxes.sum(2, keepdim=True).gt_(0.0)

        pred_bboxes = self.bbox_decode(anchor_points, pred_distri)  

        _, target_bboxes, target_scores, fg_mask, _ = self.assigner(
            pred_scores.detach().sigmoid(),
            (pred_bboxes.detach() * stride_tensor).type(gt_bboxes.dtype),
            anchor_points * stride_tensor,
            gt_labels,
            gt_bboxes,
            mask_gt,
        )

        target_scores_sum = max(target_scores.sum(), 1)

        # 1. Base CLS Loss
        loss[1] = self.bce(pred_scores, target_scores.to(dtype)).sum() / target_scores_sum
        
        # 2. EDL Loss (Merge into CLS)
        fg_mask_sum = fg_mask.sum()
        # [Fix] 显式 .item()
        if fg_mask_sum.item() > 0:
            pred_pos = pred_scores[fg_mask]
            target_pos = target_scores[fg_mask]
            
            real_model = self.model.module if hasattr(self.model, 'module') else self.model
            current_epoch = real_model.trainer.epoch if hasattr(real_model, 'trainer') else 0
            
            if pred_pos.shape[-1] != target_pos.shape[-1]:
                min_c = min(pred_pos.shape[-1], target_pos.shape[-1])
                pred_pos = pred_pos[:, :min_c]
                target_pos = target_pos[:, :min_c]

            loss_edl = self.edl_loss(pred_pos, target_pos, current_epoch)
            edl_gain = 0.5 if current_epoch > 5 else 0.1
            loss[1] += edl_gain * loss_edl 

        loss[1] *= self.hyp.cls

        # 3. Box & DFL Loss
        # [Fix] 显式 .item()
        if fg_mask_sum.item() > 0:
            loss[0], loss[2] = self.bbox_loss(
                pred_distri, pred_bboxes, anchor_points, target_bboxes / stride_tensor,
                target_scores, target_scores_sum, fg_mask,
            )
        loss[0] *= self.hyp.box
        loss[2] *= self.hyp.dfl
        
        # 4. Manifold Contrastive Loss (Merge into CLS)
        intermediate_manifold_loss = torch.tensor(0.0, device=self.device)
        real_model = self.model.module if hasattr(self.model, 'module') else self.model
        
        for m in real_model.modules():
            if hasattr(m, 'manifold_loss') and isinstance(m.manifold_loss, torch.Tensor):
                # [Fix] 显式 .item()
                if m.manifold_loss.requires_grad or m.manifold_loss.item() > 0:
                    intermediate_manifold_loss += m.manifold_loss.to(self.device)

        manifold_targets = torch.cat((
            batch['batch_idx'].view(-1, 1), batch['cls'].view(-1, 1), batch['bboxes']
        ), 1).to(self.device)
        
        loss_manifold_contrastive = self.manifold_loss(raw_features, manifold_targets, self.strides_list)
        
        # 将流形惩罚隐式融入 cls_loss 之中，保证网络学到几何特征，且不破坏 YOLO Validator
        loss[1] += (loss_manifold_contrastive + intermediate_manifold_loss)

        total_loss = loss.sum()
        return total_loss * batch_size, loss.detach()


